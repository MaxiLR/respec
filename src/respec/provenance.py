"""Where each skill of a profile came from, so that agents edit a skill at
its true source and not in respec's copy.

Nothing is stored for this: a skill's provenance is derived from the sources
``profile.yaml`` records.

- ``profile-source``: the skill's source points into the profile's source.
- ``own-source``: added locally, with a source of its own (git or a folder).
- ``original``: added locally, without a source; the copy is the only one.

A skill with a source is also ``edited`` when its files no longer match the
digest of what was copied, or when the copy holds a ``.git`` entry
(:func:`respec.sources.local_git`). Without a digest that cannot be judged.

:func:`source_file` is the text of the generated ``SOURCE.md`` that
:mod:`respec.profiles` writes beside ``profile.yaml`` on every save.
"""

from __future__ import annotations

from typing import Any

from respec import profiles, sources
from respec.messages import source_label

PROFILE_SOURCE = "profile-source"
OWN_SOURCE = "own-source"
ORIGINAL = "original"

LABELS = {
    PROFILE_SOURCE: "from the profile's source",
    OWN_SOURCE: "added locally",
    ORIGINAL: "added locally, original",
}


def of(profile: profiles.Profile, skill: str) -> str:
    """The provenance of ``skill``: one of the keys of :data:`LABELS`."""
    if profile.skills[skill].source is None:
        return ORIGINAL
    if sources.from_profile_source(profile, skill):
        return PROFILE_SOURCE
    return OWN_SOURCE


def edited(profile: profiles.Profile, skill: str) -> bool | None:
    """Whether the copy of ``skill`` no longer matches what was copied, or
    holds a ``.git`` entry; None when that cannot be judged (no source, no
    digest, or unreadable files)."""
    folder = profile.path / profiles.SKILLS_DIR / skill
    try:
        recorded = sources.copied_digest(profile, skill)
        if recorded is None:
            return None
        copy = sources.fetched_digest(folder)
    except OSError:
        return None
    return copy != recorded or bool(sources.local_git(folder))


def fields(profile: profiles.Profile, skill: str) -> dict[str, Any]:
    """The ``--json`` fields of ``skill``: ``provenance``, with ``source`` and
    ``edited`` when they apply."""
    data: dict[str, Any] = {"provenance": of(profile, skill)}
    source = profile.skills[skill].source
    if source is not None:
        data["source"] = source.to_dict()
    flag = edited(profile, skill)
    if flag is not None:
        data["edited"] = flag
    return data


def label(fields: dict[str, Any]) -> str:
    """The :func:`fields` of a skill in words, with the edited flag and the
    source: ``from the profile's source, edited: /folder/skills/tdd``."""
    text = LABELS[fields["provenance"]]
    if fields.get("edited"):
        text += ", edited"
    if "source" in fields:
        text += f": {source_label(profiles.Source(**fields['source']))}"
    return text


def source_file(profile: profiles.Profile) -> str:
    """The text of ``SOURCE.md``. It depends on ``profile.yaml`` alone (never
    on the skills' files), so it stays true until the next save."""
    name = profile.name
    lines = [
        "<!-- Generated by respec. Do not edit this file: respec writes it "
        "again whenever it saves the profile. -->",
        "",
        f"# Where the skills of profile `{name}` come from",
        "",
        "This folder is respec's own copy of the profile. respec never writes "
        "to a source, so an edit made here never reaches it.",
        "",
        "- Edit a skill at its source when it has one, then run "
        f"`respec update <skill> -p {name}`.",
        "- Edit a skill here only when it is original to this copy "
        f'("{LABELS[ORIGINAL]}").',
        f"- `respec profile diff {name}` shows what differs between this copy "
        "and the profile's source.",
        "",
        "## Profile source",
        "",
    ]
    if profile.source is None:
        lines.append("This profile has no source: it was made here.")
    else:
        lines.append(f"`{source_label(profile.source)}`")
    lines += ["", "## Skills", ""]
    if not profile.skills:
        lines.append("No skills yet.")
    for skill, entry in profile.skills.items():
        text = f"- `{skill}`: {LABELS[of(profile, skill)]}"
        if entry.source is None:
            text += f"; edit it here, in `{profiles.SKILLS_DIR}/{skill}/`"
        else:
            text += f"; edit it at `{source_label(entry.source)}`"
        lines.append(text)
    return "\n".join(lines) + "\n"
